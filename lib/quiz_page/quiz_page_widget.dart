          ),
        ),
        if (_model.showAnswerReview)
          for (var i = 0; i < questions.length; i++)
            if ((questions[i].$1 ?? '').isNotEmpty)
              Padding(
                padding: const EdgeInsets.only(bottom: 12.0),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
